import {readFile,writeFile,mkdir} from 'node:fs/promises';
import vm from 'node:vm';
const root=new URL('../',import.meta.url),context={window:{}};
vm.runInNewContext(await readFile(new URL('hall-of-fame-data.js',root),'utf8'),context);
async function request(url,binary=false) {
  for(let attempt=0;attempt<3;attempt++) {
    try {
      const response=await fetch(url,{signal:AbortSignal.timeout(20000)});
      if(!response.ok)throw Error(`Roblox HTTP ${response.status}`);
      return binary?Buffer.from(await response.arrayBuffer()):await response.json();
    } catch(error) {
      if(attempt===2)throw error;
      await new Promise(resolve=>setTimeout(resolve,1000*2**attempt));
    }
  }
}
const ids=[...new Set(context.window.hallOfFameData.developers.map(person=>person.robloxUserId).filter(Number.isSafeInteger))];
const results=await Promise.all(ids.map(async id=>{
  const [user,friends,followers,following,thumbnails]=await Promise.all([
    request(`https://users.roblox.com/v1/users/${id}`),
    request(`https://friends.roblox.com/v1/users/${id}/friends/count`),
    request(`https://friends.roblox.com/v1/users/${id}/followers/count`),
    request(`https://friends.roblox.com/v1/users/${id}/followings/count`),
    request(`https://thumbnails.roblox.com/v1/users/avatar?userIds=${id}&size=420x420&format=Png&isCircular=false`)
  ]);
  if(user.id!==id||['name','displayName','description'].some(key=>typeof user[key]!=='string')||typeof user.hasVerifiedBadge!=='boolean'||[friends,followers,following].some(item=>!Number.isSafeInteger(item.count)||item.count<0))throw Error(`Invalid developer profile ${id}`);
  const thumb=thumbnails.data.find(item=>item.targetId===id&&item.state==='Completed');
  let avatar=null;
  const avatarPath=`image/developers/${id}.png`;
  if(thumb) {
    const url=new URL(thumb.imageUrl);
    if(url.protocol!=='https:'||!url.hostname.endsWith('.rbxcdn.com'))throw Error('Unexpected Roblox thumbnail host');
    avatar=await request(url,true);
    if(avatar.subarray(0,8).toString('hex')!=='89504e470d0a1a0a')throw Error('Invalid avatar PNG');
  }
  // A pending thumbnail keeps the last valid avatar rather than breaking the deployment.
  else await readFile(new URL(avatarPath,root));
  return {avatar,profile:{id,name:user.name,displayName:user.displayName,description:user.description,
    hasVerifiedBadge:user.hasVerifiedBadge,friends:friends.count,followers:followers.count,following:following.count,
    avatar:avatarPath,capturedAt:new Date().toISOString()}};
}));
await mkdir(new URL('image/developers/',root),{recursive:true});
for(const {avatar,profile} of results)if(avatar)await writeFile(new URL(profile.avatar,root),avatar);
const profiles=Object.fromEntries(results.map(({profile})=>[profile.id,profile]));
await writeFile(new URL('developer-profiles.js',root),`// Official Roblox API snapshots. Generated by scripts/sync-developers.mjs.\nwindow.developerProfiles = ${JSON.stringify(profiles,null,2)};\n`);
console.log(`Updated ${results.length} developer Roblox profiles and avatars.`);
